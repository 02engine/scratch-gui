/**
 * The single shared rule for deciding whether an opcode names an internal
 * dropdown menu block that lives only as a shadow (never a top-level block).
 * Previously three call sites re-implemented this with slightly different
 * copies of the `endsWith("_menu")`-style heuristics.
 */
export const isMenuOpcode = (opcode: unknown): boolean => {
    const normalized = String(opcode || "");
    return (
        normalized.endsWith("_menu") ||
        normalized.includes("_menu_") ||
        normalized.endsWith("_dropdown")
    );
};

